/**
 * Regenerates src/main/db/migrations.ts from the SQL files in drizzle/.
 *
 *   npx tsx src/main/db/tools/embed-migrations.ts
 *
 * Run it after every `drizzle-kit generate`. migrations.test.ts fails if the two drift apart.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { format, resolveConfig } from 'prettier'
import { readDrizzleFolder } from './drizzle-folder'

const root = resolve(import.meta.dirname, '../../../..')
const target = resolve(root, 'src/main/db/migrations.ts')
const migrations = readDrizzleFolder(resolve(root, 'drizzle'))

const source = `/**
 * GENERATED by src/main/db/tools/embed-migrations.ts from drizzle/*.sql. Do not edit by hand.
 *
 * Embedded (instead of reading drizzle/ at runtime) so the packaged app has no path to resolve:
 * the SQL ships inside the main bundle. Index i is schema version i + 1 (PRAGMA user_version).
 */
import type { EmbeddedMigration } from './migrate'

export const MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)}
`

const options = await resolveConfig(target)
writeFileSync(target, await format(source, { ...options, filepath: target }))
console.info(`Embedded ${migrations.length} migrations into ${target}`)
