import type {
  AttemptResult,
  Card,
  CardId,
  DocId,
  DocumentSummary,
  IndexState,
  IsoDate,
  ItemStatus,
  JobId,
  JobInfo,
  JobKind,
  JobState,
  OutlineItem,
  PageNotes,
  Question,
  QuestionId,
  QuizId,
  QuizMode,
  QuizResult,
  Scope,
  SearchHit,
  SrsData,
  Topic,
  TopicEstimates,
  TopicId,
  UsageSummary,
  Rating
} from '@shared/domain'
import type { ExamPlan, MasteryBelief } from '@shared/planner/types'
import type { AiTask, Usage } from '@shared/ai/provider'
import type { Settings } from '@shared/settings'

/**
 * Persistence contract (owner: data work package). SQLite via better-sqlite3 + drizzle, FTS5 for search.
 * All methods are synchronous (better-sqlite3). Ids are generated by the repository (crypto.randomUUID).
 */

// ---------------------------------------------------------------- inputs

export interface NewDocument {
  sha256: string
  title: string
  storedPath: string
  pageCount: number
  outline: OutlineItem[]
}

export interface NewPage {
  page: number
  label: string | null
  text: string
  charCount: number
  hasTextLayer: boolean
}

export interface ChunkRow {
  index: number
  startPage: number
  endPage: number
  path: string
  bytes: number
}

export type PageIndexUpdate = Omit<PageNotes, 'docId' | 'label' | 'indexed'>

export interface NewTopic {
  key: string
  parentKey: string | null
  title: string
  pageStart: number
  pageEnd: number
  objectives: string[]
  /** prerequisites inside estimates are topic KEYS here; the repo resolves them to ids. */
  estimates: TopicEstimates | null
}

export type NewCard = Omit<Card, 'id' | 'srs' | 'createdAt' | 'status'>
export type NewQuestion = Omit<Question, 'id' | 'createdAt' | 'status'>

// ---------------------------------------------------------------- repositories

export interface DocumentRepo {
  /** Insert or return the existing document with the same sha256. */
  upsert(doc: NewDocument): { id: DocId; created: boolean }
  get(docId: DocId):
    | (DocumentSummary & {
        sha256: string
        storedPath: string
        outline: OutlineItem[]
        language: string | null
      })
    | null
  list(): DocumentSummary[]
  rename(docId: DocId, title: string): void
  setLastPage(docId: DocId, page: number): void
  setLanguage(docId: DocId, language: string): void
  setIndexState(docId: DocId, state: IndexState, error?: string | null): void
  delete(docId: DocId): void
}

export interface PageRepo {
  /** Insert page texts and refresh the FTS index for the document. */
  insertPages(docId: DocId, pages: NewPage[]): void
  setChunks(docId: DocId, chunks: ChunkRow[]): void
  chunks(docId: DocId): ChunkRow[]
  text(docId: DocId, page: number): string
  notes(docId: DocId, page: number): PageNotes | null
  notesInRange(docId: DocId, from: number, to: number): PageNotes[]
  /** Store AI index output for one page and refresh its FTS row (summary + key points are searchable). */
  saveIndex(docId: DocId, page: number, update: PageIndexUpdate): void
  indexedPages(docId: DocId): number[]
  search(query: string, docId: DocId | null, limit: number): SearchHit[]
}

export interface TopicRepo {
  /** Replace all topics of a document (topic map rebuild). Returns topics with ids. */
  replaceAll(docId: DocId, topics: NewTopic[]): Topic[]
  list(docId: DocId): Topic[]
  get(topicId: TopicId): Topic | null
  /** Topic whose page range contains the page (deepest match). */
  forPage(docId: DocId, page: number): Topic | null
  updateEstimates(topicId: TopicId, estimates: TopicEstimates): void
  mastery(topicId: TopicId): MasteryBelief | null
  /** Add quiz evidence to a topic's Beta belief. */
  addMasteryEvidence(topicId: TopicId, correct: number, incorrect: number): MasteryBelief
  minutesSpent(topicId: TopicId): number
}

export interface CardRepo {
  insertMany(cards: NewCard[], now: IsoDate): Card[]
  get(cardId: CardId): Card | null
  list(scope: Scope, includeInactive: boolean): Card[]
  fronts(docId: DocId): string[]
  due(docId: DocId | null, now: IsoDate, limit: number): Card[]
  update(cardId: CardId, patch: { front?: string; back?: string; status?: ItemStatus }): Card
  saveReview(
    cardId: CardId,
    srs: SrsData,
    log: { rating: Rating; reviewedAt: IsoDate; elapsedMs: number }
  ): Card
  stats(
    docId: DocId | null,
    now: IsoDate
  ): { due: number; new: number; learning: number; review: number; total: number }
}

export interface QuestionRepo {
  insertMany(questions: NewQuestion[], now: IsoDate): Question[]
  get(questionId: QuestionId): Question | null
  list(scope: Scope, opts: { purpose: 'page_check' | 'any'; includeInactive: boolean }): Question[]
  stems(docId: DocId): string[]
  setStatus(questionId: QuestionId, status: ItemStatus, reason?: string): void
  /** Question ids the user got wrong recently and has not answered correctly since. */
  mistakes(docId: DocId, limit: number): QuestionId[]
}

export interface QuizRepo {
  create(
    quiz: { docId: DocId; mode: QuizMode; scope: Scope; questionIds: QuestionId[]; timeLimit: number | null },
    now: IsoDate
  ): QuizId
  get(quizId: QuizId): {
    id: QuizId
    docId: DocId
    mode: QuizMode
    scope: Scope
    questionIds: QuestionId[]
    timeLimit: number | null
    createdAt: IsoDate
    finishedAt: IsoDate | null
  } | null
  saveAttempt(
    quizId: QuizId,
    attempt: AttemptResult,
    response: unknown,
    elapsedMs: number,
    now: IsoDate
  ): void
  attempts(quizId: QuizId): AttemptResult[]
  finish(quizId: QuizId, result: QuizResult): void
  history(docId: DocId, limit: number): QuizResult[]
}

export interface ReadingRepo {
  track(docId: DocId, page: number, seconds: number, now: IsoDate): void
  secondsOnPage(docId: DocId, page: number): number
  /** Average seconds per page over pages read for at least a few seconds; null if too little data. */
  averageSecondsPerPage(docId: DocId): number | null
}

export interface PlanRepo {
  get(docId: DocId): ExamPlan | null
  save(plan: Omit<ExamPlan, 'id' | 'createdAt' | 'updatedAt'>, now: IsoDate): ExamPlan
}

export interface JobRow {
  id: JobId
  kind: JobKind
  docId: DocId | null
  payload: unknown
  priority: number
  dedupeKey: string | null
  state: JobState
  progress: number
  label: string
  error: string | null
  attempts: number
  runAfter: IsoDate | null
  createdAt: IsoDate
  updatedAt: IsoDate
}

export interface JobRepo {
  insert(
    job: Omit<JobRow, 'id' | 'state' | 'progress' | 'error' | 'attempts' | 'createdAt' | 'updatedAt'>,
    now: IsoDate
  ): JobRow
  /** Existing non-finished job with the same dedupe key, if any. */
  findActive(dedupeKey: string): JobRow | null
  /** Highest priority queued job whose runAfter has passed. */
  nextRunnable(now: IsoDate, excludeKinds?: JobKind[]): JobRow | null
  update(
    id: JobId,
    patch: Partial<
      Pick<JobRow, 'state' | 'progress' | 'label' | 'error' | 'attempts' | 'runAfter' | 'priority'>
    >,
    now: IsoDate
  ): JobRow
  get(id: JobId): JobRow | null
  list(docId: DocId | null, limit: number): JobInfo[]
  /** On startup: jobs left 'running' by a crash go back to 'queued'. */
  requeueInterrupted(now: IsoDate): number
}

export interface UsageRepo {
  record(
    entry: { task: AiTask; model: string; provider: string; docId: DocId | null; usage: Usage },
    now: IsoDate
  ): void
  summary(now: IsoDate): UsageSummary
  monthSpendUsd(now: IsoDate): number
}

export interface SettingsRepo {
  get(): Settings
  update(patch: Partial<Settings>): Settings
  /** Encrypted secret blobs (encryption is done by the caller with safeStorage). */
  getSecret(name: string): Buffer | null
  setSecret(name: string, value: Buffer | null): void
}

export interface Database {
  documents: DocumentRepo
  pages: PageRepo
  topics: TopicRepo
  cards: CardRepo
  questions: QuestionRepo
  quizzes: QuizRepo
  reading: ReadingRepo
  plans: PlanRepo
  jobs: JobRepo
  usage: UsageRepo
  settings: SettingsRepo
  transaction<T>(fn: () => T): T
  close(): void
}

/** Open (and migrate) the database. ':memory:' is allowed for tests. */
export type OpenDatabase = (file: string) => Database
